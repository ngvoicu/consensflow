//! What the release's tests run on: a checkout in a temporary tree with two
//! bare repositories for its remotes, `origin` and `upstream`, which `git`
//! really pushes to; and a GitHub that is a script. `gh` lists, shows and
//! starts runs the test sets up, a push of `main` to upstream starts CI, a push
//! of a tag starts the Release run, which (when it ends green) puts the version
//! on the feeds a release of its channel moves; `curl` reads those feeds; and
//! `cargo update` writes the lockfile's version as cargo does. Nothing here
//! reaches GitHub or moves a feed.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::Duration;

use cf_base::env::Env;
use serde_json::json;

use crate::process::{self, Captured, Invocation};
use crate::release::system::System;
use crate::release::{Error, Pace, Release};

/// Writes `text` to `path`, in folders made for it.
pub fn write(path: &Path, text: &str) {
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, text).unwrap();
}

/// What `git` says to `args` in `dir`, which must end well.
pub fn git(dir: &Path, args: &[&str]) -> String {
    let ran = process::capture(
        &Invocation::new("git", dir).args(args.iter().copied()),
        &Env::from_process(),
    )
    .unwrap();
    assert_eq!(
        ran.code,
        0,
        "git {args:?} in {}: {}",
        dir.display(),
        ran.stderr
    );
    ran.stdout.trim().to_owned()
}

/// Whether `git` ends `args` with 0 in `dir`.
pub fn git_says_yes(dir: &Path, args: &[&str]) -> bool {
    process::capture(
        &Invocation::new("git", dir).args(args.iter().copied()),
        &Env::from_process(),
    )
    .unwrap()
    .code
        == 0
}

/// The version files of a checkout at `version`, as the repository writes them,
/// with two workspace crates and one from the registry in the lockfile.
pub fn version_files(version: &str) -> Vec<(&'static str, String)> {
    vec![
        (
            "package.json",
            format!("{{\n  \"name\": \"consensflow\",\n  \"version\": \"{version}\",\n  \"private\": true\n}}\n"),
        ),
        (
            "package-lock.json",
            format!(
                "{{\n  \"name\": \"consensflow\",\n  \"version\": \"{version}\",\n  \"lockfileVersion\": 3,\n  \
                 \"packages\": {{\n    \"\": {{\n      \"name\": \"consensflow\",\n      \"version\": \"{version}\"\n    }},\n    \
                 \"node_modules/semver\": {{\n      \"version\": \"7.6.0\"\n    }}\n  }}\n}}\n"
            ),
        ),
        (
            "Cargo.toml",
            format!("[workspace]\nmembers = [\"crates/cf\", \"tools/xtask\"]\n\n[workspace.package]\nversion = \"{version}\"\nedition = \"2024\"\n"),
        ),
        (
            "Cargo.lock",
            format!(
                "# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = \"cf\"\n\
                 version = \"{version}\"\ndependencies = [\n \"serde\",\n]\n\n[[package]]\nname = \"serde\"\n\
                 version = \"1.0.228\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\n\n\
                 [[package]]\nname = \"xtask\"\nversion = \"{version}\"\n"
            ),
        ),
        (
            "app/src-tauri/tauri.conf.json",
            format!("{{\n  \"productName\": \"ConsensFlow\",\n  \"version\": \"{version}\"\n}}\n"),
        ),
    ]
}

/// A checkout and its two remotes, in a temporary tree, and the notes of a release.
pub struct World {
    /// The tree everything is in, removed with the world.
    _temp: tempfile::TempDir,
    pub root: PathBuf,
    pub origin: PathBuf,
    pub upstream: PathBuf,
    pub notes: PathBuf,
}

impl World {
    /// A checkout on `main` at `version`, committed and pushed to both remotes.
    pub fn new(version: &str) -> Self {
        let temp = tempfile::tempdir().unwrap();
        let root = temp.path().join("checkout");
        let origin = temp.path().join("origin.git");
        let upstream = temp.path().join("upstream.git");
        fs::create_dir_all(&root).unwrap();
        git(&root, &["init", "-q", "-b", "main"]);
        // The checkout's own settings, before any the machine has.
        for (key, value) in [
            ("user.name", "Release Test"),
            ("user.email", "release@example.com"),
            ("commit.gpgsign", "false"),
            ("tag.gpgsign", "false"),
            ("core.autocrlf", "false"),
        ] {
            git(&root, &["config", key, value]);
        }
        for remote in [&origin, &upstream] {
            fs::create_dir_all(remote).unwrap();
            git(remote, &["init", "-q", "--bare", "-b", "main"]);
        }
        let notes = temp.path().join("notes.txt");
        write(
            &notes,
            "The title of the release\n\nWhat changed, for the people updating.\n",
        );
        let world = Self {
            _temp: temp,
            root,
            origin,
            upstream,
            notes,
        };
        write(&world.root.join(".gitignore"), "app/src-tauri/target/\n");
        write(&world.root.join("README.md"), "ConsensFlow\n");
        world.at_version(version, "the first commit");
        for remote in ["origin", "upstream"] {
            let path = if remote == "origin" {
                &world.origin
            } else {
                &world.upstream
            };
            git(
                &world.root,
                &["remote", "add", remote, &path.to_string_lossy()],
            );
        }
        world.push_main();
        world
    }

    /// Writes the version files at `version` and commits every change as `message`.
    pub fn at_version(&self, version: &str, message: &str) {
        for (path, text) in version_files(version) {
            write(&self.root.join(path), &text);
        }
        self.commit(message);
    }

    /// Commits every change of the checkout as `message`.
    pub fn commit(&self, message: &str) {
        git(&self.root, &["add", "-A"]);
        git(&self.root, &["commit", "-q", "-m", message]);
    }

    pub fn push_main(&self) {
        for remote in ["origin", "upstream"] {
            git(&self.root, &["push", "-q", remote, "main"]);
        }
    }

    /// The commit `reference` names in the checkout.
    pub fn commit_of(&self, reference: &str) -> String {
        git(
            &self.root,
            &["rev-parse", &format!("{reference}^{{commit}}")],
        )
    }

    pub fn head(&self) -> String {
        self.commit_of("HEAD")
    }

    /// `version` released: its tag on HEAD, pushed to both remotes.
    pub fn released(&self, version: &str) {
        let tag = format!("v{version}");
        git(&self.root, &["tag", "-a", &tag, "-m", version]);
        for remote in ["origin", "upstream"] {
            git(&self.root, &["push", "-q", remote, &tag]);
        }
    }

    /// The commit the tag `tag` names in the bare repository `remote`, if it has it.
    pub fn tagged(remote: &Path, tag: &str) -> Option<String> {
        let reference = format!("refs/tags/{tag}^{{commit}}");
        git_says_yes(remote, &["rev-parse", "-q", "--verify", &reference])
            .then(|| git(remote, &["rev-parse", &reference]))
    }

    /// The release run of `options` on `system`, with no waits: what it answered
    /// and what it said on the way.
    pub fn run(
        &self,
        system: &mut Fake,
        run: fn(&mut Release, &crate::release::Options) -> Result<String, Error>,
        options: &crate::release::Options,
    ) -> (Result<String, Error>, String) {
        let mut said = Vec::new();
        let mut release = Release {
            root: self.root.clone(),
            system,
            said: &mut said,
            pace: Pace {
                appear: Duration::ZERO,
                appear_attempts: 5,
                poll: Duration::ZERO,
                feed: Duration::ZERO,
                feed_attempts: 5,
            },
        };
        let outcome = run(&mut release, options);
        (outcome, String::from_utf8(said).unwrap())
    }
}

/// A run of a workflow, as GitHub keeps it.
#[derive(Debug, Clone)]
pub struct FakeRun {
    pub id: u64,
    pub workflow: String,
    pub commit: String,
    pub event: String,
    pub conclusion: String,
    pub jobs: Vec<(String, String)>,
    /// The looks at it before it has ended.
    pub running_for: u32,
    /// The lists of runs it is not yet in.
    pub unlisted_for: u32,
}

/// The machine a release test runs on: real `git`, and the rest a script.
pub struct Fake {
    upstream: PathBuf,
    pub runs: Vec<FakeRun>,
    /// What each feed serves, by its name.
    pub feeds: BTreeMap<String, String>,
    /// What a finished Release run puts on a feed, and the reads of it before it shows.
    waiting: Vec<(String, String, u32)>,
    /// The reads of a feed before a publish shows on it.
    pub feed_lag: u32,
    /// How each run of a workflow by an event ends; `success` where none is named.
    pub conclusions: BTreeMap<(&'static str, &'static str), &'static str>,
    /// The jobs of a CI run.
    pub ci_jobs: Vec<(&'static str, &'static str)>,
    /// The looks at a new run before it ends, and the lists it is not yet in.
    pub running_for: u32,
    pub unlisted_for: u32,
    /// Whether a green Release run publishes, and whether an alpha's moves
    /// `feed-stable` too, as no release of the alpha channel may.
    pub publishes: bool,
    pub alpha_moves_stable: bool,
    /// What `cargo update` writes beyond the version: text added to the
    /// lockfile, and a file of its own.
    pub cargo_adds_to_the_lockfile: Option<&'static str>,
    pub cargo_writes: Option<(&'static str, &'static str)>,
    /// The remote that refuses pushes, as one whose hook declines them, and
    /// the start of the references it refuses (`""` for all).
    pub refuses_pushes: Option<&'static str>,
    pub refused_refs: &'static str,
    /// Reads of a feed that fail, in order: the feed, and curl's status
    /// (22 for a 404, 28 for a time-out, 6 for a name that does not resolve).
    pub failing_reads: Vec<(&'static str, i32)>,
    /// Reads that fail once a tag is pushed: the feeds' answers during and after the release.
    pub failing_after_the_tag: Vec<(&'static str, i32)>,
    /// Whether a fetch of a tag by name fails, as one does when the network does.
    pub tag_fetch_fails: bool,
    /// Whether a tag pushed to upstream starts its Release run.
    pub tags_start_runs: bool,
    /// Whether every `gh` fails, as it does when it is not logged in.
    pub gh_fails: bool,
    /// Every program run, in order.
    pub ran: Vec<Invocation>,
    pub pauses: u32,
}

impl Fake {
    /// GitHub as `world`'s upstream has it, with feeds that serve
    /// `alpha_feed` and `stable_feed`.
    pub fn new(world: &World, alpha_feed: &str, stable_feed: &str) -> Self {
        let feeds = [("feed-alpha", alpha_feed), ("feed-stable", stable_feed)]
            .into_iter()
            .map(|(feed, version)| (feed.to_owned(), latest(version)))
            .collect();
        Self {
            upstream: world.upstream.clone(),
            runs: Vec::new(),
            feeds,
            waiting: Vec::new(),
            feed_lag: 0,
            conclusions: BTreeMap::new(),
            ci_jobs: vec![
                ("gate (macos-latest)", "success"),
                ("gate (windows-latest)", "success"),
            ],
            running_for: 1,
            unlisted_for: 0,
            publishes: true,
            alpha_moves_stable: false,
            cargo_adds_to_the_lockfile: None,
            cargo_writes: None,
            refuses_pushes: None,
            refused_refs: "",
            failing_reads: Vec::new(),
            failing_after_the_tag: Vec::new(),
            tag_fetch_fails: false,
            tags_start_runs: true,
            gh_fails: false,
            ran: Vec::new(),
            pauses: 0,
        }
    }

    /// The same, with CI's push run on `commit` there already and green.
    pub fn with_ci_on(world: &World, commit: &str, alpha_feed: &str, stable_feed: &str) -> Self {
        let mut fake = Self::new(world, alpha_feed, stable_feed);
        fake.start("ci.yml", commit, "push");
        fake
    }

    /// The lines of what was run, as a person reads each.
    pub fn lines(&self) -> Vec<String> {
        self.ran.iter().map(Invocation::display).collect()
    }

    /// Where in what was run the first line that starts with `start` is.
    pub fn when(&self, start: &str) -> Option<usize> {
        self.lines().iter().position(|line| line.starts_with(start))
    }

    /// The runs of `workflow` by `event`.
    pub fn runs_of(&self, workflow: &str, event: &str) -> Vec<&FakeRun> {
        self.runs
            .iter()
            .filter(|run| run.workflow == workflow && run.event == event)
            .collect()
    }

    /// What `feed` serves, by its version.
    pub fn serves(&self, feed: &str) -> Option<String> {
        let body = self.feeds.get(feed)?;
        let document: serde_json::Value = serde_json::from_str(body).ok()?;
        document["version"].as_str().map(str::to_owned)
    }

    /// A run of `workflow` on `commit` by `event`, as GitHub starts one: its id.
    pub fn start(&mut self, workflow: &str, commit: &str, event: &str) -> u64 {
        let key = self
            .conclusions
            .keys()
            .find(|(named, by)| *named == workflow && *by == event)
            .copied();
        let conclusion = key
            .and_then(|key| self.conclusions.get(&key).copied())
            .unwrap_or("success");
        let jobs = if workflow == "ci.yml" {
            self.ci_jobs
                .iter()
                .map(|(job, ended)| ((*job).to_owned(), (*ended).to_owned()))
                .collect()
        } else {
            vec![
                ("mac".to_owned(), conclusion.to_owned()),
                ("windows / build".to_owned(), conclusion.to_owned()),
            ]
        };
        let id = 1000 + self.runs.len() as u64;
        self.runs.push(FakeRun {
            id,
            workflow: workflow.to_owned(),
            commit: commit.to_owned(),
            event: event.to_owned(),
            conclusion: conclusion.to_owned(),
            jobs,
            running_for: self.running_for,
            unlisted_for: self.unlisted_for,
        });
        id
    }

    /// What upstream's `reference` names.
    fn upstream_commit(&self, reference: &str) -> String {
        git(
            &self.upstream,
            &["rev-parse", &format!("{reference}^{{commit}}")],
        )
    }

    /// What GitHub does when upstream is pushed `refspec`.
    fn pushed(&mut self, refspec: &str) {
        let target = refspec.rsplit(':').next().unwrap_or(refspec);
        if let Some(version) = target.strip_prefix('v') {
            self.failing_reads.append(&mut self.failing_after_the_tag);
            if !self.tags_start_runs {
                return;
            }
            let commit = self.upstream_commit(target);
            let id = self.start("release.yml", &commit, "push");
            let green = self
                .runs
                .iter()
                .any(|run| run.id == id && run.conclusion == "success");
            if green && self.publishes {
                let mut feeds = vec!["feed-alpha"];
                if !version.contains('-') || self.alpha_moves_stable {
                    feeds.push("feed-stable");
                }
                for feed in feeds {
                    self.waiting
                        .push((feed.to_owned(), latest(version), self.feed_lag));
                }
            }
        } else if target == "main" || target == "refs/heads/main" {
            let commit = self.upstream_commit("main");
            self.start("ci.yml", &commit, "push");
        }
    }

    fn gh(&mut self, args: &[String]) -> Captured {
        if self.gh_fails {
            return Captured {
                code: 4,
                stdout: String::new(),
                stderr: "To get started with GitHub CLI, please run:  gh auth login".to_owned(),
            };
        }
        let flag = |name: &str| {
            args.iter()
                .position(|arg| arg == name)
                .and_then(|at| args.get(at + 1))
                .cloned()
        };
        let words: Vec<&str> = args.iter().map(String::as_str).collect();
        match words.as_slice() {
            ["run", "list", ..] => {
                let workflow = flag("--workflow").unwrap();
                let (commit, event) = (flag("--commit"), flag("--event"));
                let mut newest = None;
                for run in &mut self.runs {
                    let fits = run.workflow == workflow
                        && commit.as_ref().is_none_or(|commit| run.commit == *commit)
                        && event.as_ref().is_none_or(|event| run.event == *event);
                    if !fits {
                        continue;
                    }
                    if run.unlisted_for > 0 {
                        run.unlisted_for -= 1;
                        continue;
                    }
                    newest = newest.max(Some(run.id));
                }
                let listed: Vec<_> = newest
                    .map(|id| json!({ "databaseId": id }))
                    .into_iter()
                    .collect();
                said(&json!(listed).to_string())
            }
            ["run", "view", id, ..] => {
                let id: u64 = id.parse().unwrap();
                let run = self.runs.iter_mut().find(|run| run.id == id).unwrap();
                let (status, conclusion) = if run.running_for > 0 {
                    run.running_for -= 1;
                    ("in_progress", "")
                } else {
                    ("completed", run.conclusion.as_str())
                };
                let jobs: Vec<_> = run
                    .jobs
                    .iter()
                    .map(|(name, ended)| json!({ "name": name, "conclusion": ended }))
                    .collect();
                said(
                    &json!({ "status": status, "conclusion": conclusion, "jobs": jobs })
                        .to_string(),
                )
            }
            ["workflow", "run", workflow, ..] => {
                let reference = flag("--ref").unwrap();
                let commit = self.upstream_commit(&reference);
                let workflow = (*workflow).to_owned();
                self.start(&workflow, &commit, "workflow_dispatch");
                said("")
            }
            _ => panic!("gh was asked what GitHub's script does not answer: {args:?}"),
        }
    }

    fn curl(&mut self, address: &str) -> Captured {
        let feed = address
            .strip_suffix("/latest.json")
            .and_then(|rest| rest.rsplit('/').next())
            .unwrap()
            .to_owned();
        let mut still = Vec::new();
        for (named, body, reads) in std::mem::take(&mut self.waiting) {
            if named != feed {
                still.push((named, body, reads));
            } else if reads == 0 {
                self.feeds.insert(named, body);
            } else {
                still.push((named, body, reads - 1));
            }
        }
        self.waiting = still;
        if let Some(at) = self
            .failing_reads
            .iter()
            .position(|(named, _)| *named == feed)
        {
            let (_, code) = self.failing_reads.remove(at);
            return Captured {
                code,
                stdout: String::new(),
                stderr: format!("curl: ({code}) the read failed"),
            };
        }
        match self.feeds.get(&feed) {
            Some(body) => said(body),
            None => Captured {
                code: 22,
                stdout: String::new(),
                stderr: "curl: (22) The requested URL returned error: 404".to_owned(),
            },
        }
    }

    /// `cargo update --workspace --offline` in `tree`: the workspace's crates in
    /// the lockfile take the version the manifest says, as cargo writes it.
    fn cargo(&self, tree: &Path) -> Captured {
        let manifest = fs::read_to_string(tree.join("Cargo.toml")).unwrap();
        let version = manifest
            .lines()
            .find_map(|line| line.strip_prefix("version = "))
            .unwrap()
            .to_owned();
        let lockfile = tree.join("Cargo.lock");
        let mut lines: Vec<String> = fs::read_to_string(&lockfile)
            .unwrap()
            .lines()
            .map(str::to_owned)
            .collect();
        for at in 1..lines.len() {
            let member = lines[at - 1] == "name = \"cf\"" || lines[at - 1] == "name = \"xtask\"";
            if member && lines[at].starts_with("version = ") {
                lines[at] = format!("version = {version}");
            }
        }
        let mut text = lines.join("\n") + "\n";
        if let Some(more) = self.cargo_adds_to_the_lockfile {
            text += more;
        }
        fs::write(&lockfile, text).unwrap();
        if let Some((path, text)) = self.cargo_writes {
            write(&tree.join(path), text);
        }
        said("")
    }
}

/// What a program that wrote `stdout` and ended well left.
fn said(stdout: &str) -> Captured {
    Captured {
        code: 0,
        stdout: stdout.to_owned(),
        stderr: String::new(),
    }
}

/// A feed's latest.json, naming `version`.
pub fn latest(version: &str) -> String {
    json!({ "version": version, "notes": "notes", "platforms": {} }).to_string()
}

impl System for Fake {
    fn capture(&mut self, invocation: &Invocation) -> Result<Captured, Error> {
        self.ran.push(invocation.clone());
        let args: Vec<String> = invocation
            .args
            .iter()
            .map(|arg| arg.to_string_lossy().into_owned())
            .collect();
        match invocation.program.to_string_lossy().as_ref() {
            "git" => {
                // `push -q <remote> <refspec>`
                let pushing_to = (args.first().is_some_and(|word| word == "push"))
                    .then(|| args.get(2).cloned())
                    .flatten();
                let refused = args
                    .get(3)
                    .is_some_and(|refspec| refspec.starts_with(self.refused_refs));
                if pushing_to.is_some() && pushing_to.as_deref() == self.refuses_pushes && refused {
                    return Ok(Captured {
                        code: 1,
                        stdout: String::new(),
                        stderr: "! [remote rejected] (pre-receive hook declined)".to_owned(),
                    });
                }
                let fetching_a_tag = args.first().is_some_and(|word| word == "fetch")
                    && args.iter().any(|arg| arg.starts_with("+refs/tags/"));
                if fetching_a_tag && self.tag_fetch_fails {
                    return Ok(Captured {
                        code: 128,
                        stdout: String::new(),
                        stderr: "fatal: unable to access the remote: Could not resolve host"
                            .to_owned(),
                    });
                }
                let ran = process::capture(invocation, &Env::from_process())?;
                if ran.code == 0 && pushing_to.as_deref() == Some("upstream") {
                    self.pushed(&args[3]);
                }
                Ok(ran)
            }
            "gh" => Ok(self.gh(&args)),
            "curl" => Ok(self.curl(args.last().unwrap())),
            "cargo" => {
                assert_eq!(args, ["update", "--workspace", "--offline"]);
                Ok(self.cargo(&invocation.cwd))
            }
            program => panic!("a release does not run {program}"),
        }
    }

    fn pause(&mut self, _duration: Duration) {
        self.pauses += 1;
    }
}
