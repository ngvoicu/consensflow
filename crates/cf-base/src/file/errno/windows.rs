/// The name libuv gives the system's error `code`; none for a code that is
/// not in the table, which libuv calls `UV_UNKNOWN`. A code that is not
/// above zero is one libuv hands on as it is, already one of its own: no
/// failed call carries one.
pub(super) fn name(code: i32) -> Option<&'static str> {
    let code = u32::try_from(code).ok().filter(|code| *code > 0)?;
    TRANSLATION
        .iter()
        .find(|(known, _)| *known == code)
        .map(|(_, name)| *name)
}

